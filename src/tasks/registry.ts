import type { Component } from 'vue'

/**
 * Реестр контрольных задач.
 *
 * Каждая задача добавляется сюда по мере выполнения — роутер и главная
 * страница строятся автоматически из этого списка.
 * Под каждую задачу — своя страница (slug) и свой компонент.
 */
export interface TaskMeta {
  /** Порядковый номер задачи (0, 1, 2, ...). */
  id: number
  /** Короткий slug: 0-base, 1-sort, ... — используется в URL. */
  slug: string
  /** Название задачи для ссылки на главной. */
  title: string
  /** Краткое описание. */
  description: string
  /** Async-компонент страницы задачи. */
  component: (() => Promise<Component>) | Component
}

// Пока ни одной содержательной задачи нет — задача 0 заключается в самой
// переработке шаблона. По мере добавления задач описывайте их здесь.
export const tasks: TaskMeta[] = []